"""Generate the stress roadmap: 50 teams, 500 projects, 60 months (RS NF-3, AT-44).

Deterministic (fixed seed; no clock). The file is valid in delay, overflow and error-free delay mode: at most one
ongoing project per team and only in teams with 2+ slots, dependencies point to earlier finite projects.

Usage: python tools/gen_stress.py [OUTPUT.yaml | -] [--teams 50] [--projects 500] [--months 60] [--seed 7]
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

SIZES = (("XS", 1), ("S", 2), ("M", 4), ("L", 8), ("XL", 13))
COLORS = ("indigo", "green", "orange", "pink", "sky", "amber", "violet", "teal", "lime", "sand")
WORDS = (
    "Płatności",
    "Rozliczenia",
    "Karty",
    "BLIK",
    "Portfel",
    "Raporty",
    "Onboarding",
    "Fraud",
    "Checkout",
    "Łańcuch źródeł",
    "API",
    "Migracja",
    "Tokenizacja",
    "Audyt",
    "Integracja",
    "Panel",
)
TEAMS_PER_SUBDOMAIN = 5


def _q(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(teams: int = 50, projects: int = 500, months: int = 60, seed: int = 7) -> str:
    rng = random.Random(seed)
    start_year, start_month = 2027, 1

    def month(offset: int) -> str:
        index = start_year * 12 + start_month - 1 + offset
        return f"{index // 12:04d}-{index % 12 + 1:02d}"

    lines = [
        "# Generated by tools/gen_stress.py — stress fixture (RS NF-3, AT-44). Do not edit by hand.",
        "version: 1",
        "",
        "roadmap:",
        f"  title: {_q(f'Stress roadmap – {teams} teams, {projects} projects')}",
        "  subtitle: Wygenerowany plan obciążeniowy",
        f"  horizon: {{ start: {month(0)}, end: {month(months - 1)} }}",
        "  today: 2027-06-15",
        "  content_language: pl",
        "",
        "sizes:",
        *(f"  {label}: {weeks}" for label, weeks in SIZES),
        "",
        "scheduling:",
        "  on_conflict: delay",
        "",
        "subdomains:",
    ]
    team_ids: list[str] = []
    team_slots: dict[str, int] = {}
    subdomain_count = (teams + TEAMS_PER_SUBDOMAIN - 1) // TEAMS_PER_SUBDOMAIN
    for s in range(subdomain_count):
        lines += [
            f"  - id: sd-{s + 1:02d}",
            f"    name: {_q(f'Obszar {s + 1} – {WORDS[s % len(WORDS)]}')}",
            "    teams:",
        ]
        for t in range(TEAMS_PER_SUBDOMAIN):
            n = s * TEAMS_PER_SUBDOMAIN + t
            if n >= teams:
                break
            tid = f"team-{n + 1:02d}"
            slots = rng.randint(1, 4)
            team_ids.append(tid)
            team_slots[tid] = slots
            lines += [
                f"      - id: {tid}",
                f"        name: {_q(f'Zespół {n + 1}')}",
                f"        parallel_projects: {slots}",
                f"        capacity: {{ developers: {rng.randint(1, 9)}, product_managers: 1, "
                f"analysts: {rng.randint(0, 2)}, testers: {rng.randint(0, 3)} }}",
            ]
    lines += ["", "projects:"]
    finite: list[str] = []
    has_ongoing: set[str] = set()
    for i in range(projects):
        tid = team_ids[i % len(team_ids)]
        pid = f"p-{i + 1:03d}"
        name = f"{WORDS[rng.randrange(len(WORDS))]} {i + 1}"
        lines += [f"  - id: {pid}", f"    name: {_q(name)}", f"    team: {tid}"]
        ongoing = team_slots[tid] >= 2 and tid not in has_ongoing and rng.random() < 0.15
        if ongoing:
            has_ongoing.add(tid)
            lines.append("    ongoing: true")
        else:
            lines.append(f"    size: {SIZES[rng.randrange(len(SIZES))][0]}")
        if rng.random() < 0.9:
            lines.append(f"    start: {month(rng.randrange(months - 3))}")
        if finite and rng.random() < 0.2:
            deps = sorted(set(rng.sample(finite[-40:], k=min(len(finite[-40:]), rng.randint(1, 2)))))
            lines.append(f"    depends_on: [{', '.join(deps)}]")
        if rng.random() < 0.05:
            lines.append(f"    color: {COLORS[rng.randrange(len(COLORS))]}")
        if rng.random() < 0.5:
            lines.append(f"    description: {_q(f'Opis projektu {i + 1}: zażółć gęślą jaźń')}")
        if not ongoing:
            finite.append(pid)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("output", nargs="?", default="-")
    parser.add_argument("--teams", type=int, default=50)
    parser.add_argument("--projects", type=int, default=500)
    parser.add_argument("--months", type=int, default=60)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args(argv)
    text = generate(args.teams, args.projects, args.months, args.seed)
    data = text.encode("utf-8")
    if args.output == "-":
        sys.stdout.buffer.write(data)
        sys.stdout.buffer.flush()
    else:
        Path(args.output).write_bytes(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
