Doc = lhtml.HtmlElement


def render(plan: Plan, summary: bool = False) -> str:
    return render_html(build_page(plan, summary=summary, version="1.2.3"))


@cache
def we_html(summary: bool = False) -> str:
    return render(plankit.plan_from_file(plankit.WE), summary)


def parse(text: str) -> Doc:
    return lhtml.document_fromstring(text.encode("utf-8"))


def bar(doc: Doc, name: str) -> Doc:
    (el,) = [b for b in doc.cssselect(".rt-bar") if b.get("title").split("\n")[0] == name]
    return el


def test_file_rules() -> None:
    text = we_html()
    assert text.startswith('<!doctype html>\n<html lang="en">\n')
    assert text.endswith("</html>\n") and "\r" not in text
    doc = parse(text)
    assert doc.cssselect("meta[charset]")[0].get("charset") == "utf-8"
    assert doc.findtext(".//title") == "Scheduling worked example"
    assert len(doc.cssselect("style")) == 1 and not doc.cssselect("script")
    assert 'system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif' in text
    assert "size:A3 landscape" in text and "print-color-adjust:exact" in text and "break-inside:avoid" in text
    assert "prefers-color-scheme:dark" in text
    for attr in ("src", "href"):
        assert not [e for e in doc.iter() if isinstance(e.tag, str) and re.match(r"(https?:|//)", e.get(attr, ""))]
    assert not re.search(r"url\(\s*['\"]?(https?:|//)", text)
    assert "http:" not in text and "https:" not in text
    assert doc.cssselect(".rt-foot")[0].text_content() == "Generated by rt 1.2.3"


def test_stylesheet_is_compact_and_keeps_declarations_readable() -> None:
    css = stylesheet()
    assert "/*" not in css and "\n" not in css
    assert len(css.encode()) < 18_000
    assert compact_css("a, b {\n  color: red; /* x */\n}\n") == "a, b{color:red;}"


def test_conditional_hooks_are_absent_when_their_feature_is_off() -> None:
    doc = parse(we_html())
    assert not doc.cssselect(".rt-summary, .rt-load-cell, .rt-dep, .rt-deps")
