def test_strict_turns_warnings_into_failure_without_output() -> None:
    io = _io(b"")
    assert _pl(io, "--strict", name="teams.base.yaml.csv") == 4  # missing CSV is an I/O error
    io = _io(PL_CSV)
    assert _pl(io, "--strict") == 1
    assert io.stdout == b""
    assert _codes(io.stderr) == ["warning W020", "warning W021"]
    assert "rt: wrote" not in io.stderr


def test_quiet_drops_warnings_and_summary() -> None:
    io = _io(PL_CSV)
    assert _pl(io, "-q") == 0
    assert io.stdout == _first_line_swapped(PL_YAML, "in.csv")
    assert io.stderr == ""


def test_unwritable_output_is_exit_4() -> None:
    io = _io(MINIMAL_CSV)
    io.fail_write.add("out.yaml")
    opts = ConvertOptions(input="in.csv", default_today=TODAY, output="out.yaml")
    assert run_convert(opts, io) == 4
    assert "cannot write out.yaml" in io.stderr


def test_missing_base_is_exit_4() -> None:
    io = _io(MINIMAL_CSV)
    opts = ConvertOptions(input="in.csv", default_today=TODAY, base="nope.yaml")
    assert run_convert(opts, io) == 4
    assert "cannot read nope.yaml" in io.stderr


def test_base_errors_point_into_the_base_file() -> None:
    io = _io(MINIMAL_CSV, **{"bad.yaml": b"version: 1\nroadmap:\n  title: [x\n"})
    assert main(["convert", "in.csv", "--base", "bad.yaml", "--team", "x"], io) == 1
    assert io.stderr.startswith("bad.yaml:")
    assert io.stdout == b""


def test_csv_reference_errors_point_into_the_csv() -> None:
    csv = "name,size,team,depends_on,id\nA,M,blik,Later,a\nLater,S,blik,,\nB,S,app,A|Ghost,a\n"
    io = _io(csv.encode())
    assert main(["convert", "in.csv", "--base", "teams.base.yaml"], io) == 1
    lines = [line for line in io.stderr.splitlines() if ": error " in line]
    assert any(line.startswith("in.csv:2:4: error E037") for line in lines), io.stderr
    assert any(line.startswith("in.csv:4:4: error E034") for line in lines), io.stderr
    assert any(line.startswith("in.csv:4:5: error E023") for line in lines), io.stderr


