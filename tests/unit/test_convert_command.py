"""run_convert end to end with FakeIO (RS 6.6, AT-47 to AT-55, ST-2, CLI-7)."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pytest

from rt.cli import main
from rt.convert.command import run_convert
from rt.io.streams import FakeIO
from rt.options import ConvertOptions

FIX = Path(__file__).resolve().parents[2] / "docs" / "fixtures" / "convert"
MINIMAL_CSV = (FIX / "projects.minimal.csv").read_bytes()
MINIMAL_YAML = (FIX / "projects.minimal.expected.yaml").read_bytes()
PL_CSV = (FIX / "projects.pl.csv").read_bytes()
PL_TEXT = PL_CSV.decode("utf-8-sig")
PL_YAML = (FIX / "projects.pl.expected.yaml").read_bytes()
BASE = (FIX / "teams.base.yaml").read_bytes()
MAP = "Projekt=name,Rozmiar=size,Zespół=team,Start=start,Zależności=depends_on,Ciągły=ongoing,Opis=description"
TODAY = date(2026, 10, 24)


def _io(csv: bytes, **files: bytes) -> FakeIO:
    return FakeIO(files={"in.csv": csv, "teams.base.yaml": BASE, **files})


def _pl(io: FakeIO, *extra: str, name: str = "in.csv") -> int:
    return main(["convert", name, "--base", "teams.base.yaml", "--map", MAP, *extra], io)


def _codes(stderr: str) -> list[str]:
    return [line.split(": ")[1] for line in stderr.splitlines() if ": error " in line or ": warning " in line]


def _first_line_swapped(data: bytes, name: str) -> bytes:
    _head, rest = data.split(b"\n", 1)
    return f"# Generated by rt convert from {name}. Edit freely.".encode() + b"\n" + rest


def test_at_47_minimal_csv_to_stdout() -> None:
    io = FakeIO(files={"data/projects.minimal.csv": MINIMAL_CSV})
    assert main(["convert", "data/projects.minimal.csv"], io) == 0
    assert io.stdout == MINIMAL_YAML
    assert io.stderr == "rt: wrote <stdout> — 4 projects from projects.minimal.csv, 0 warnings\n"


def test_at_48_worked_example_to_file_with_exact_stderr() -> None:
    io = _io(b"", **{"projects.pl.csv": PL_CSV})
    assert _pl(io, "-o", "roadmap.yaml", name="projects.pl.csv") == 0
    assert io.files["roadmap.yaml"] == PL_YAML
    assert io.stdout == b""
    assert io.stderr == (
        'projects.pl.csv:1:8: warning W020: column "Właściciel" is not used and was ignored\n'
        'projects.pl.csv:5:4: warning W021: day of "2027-03-15" ignored; using 2027-03 [column "Start"]\n'
        "rt: wrote roadmap.yaml — 5 projects from projects.pl.csv, 2 warnings\n"
    )


@pytest.mark.parametrize(
    ("data", "extra"),
    [
        (
            PL_TEXT.replace(";", ",")
            .replace('"Subskrypcje, płatności cykliczne"', '"Subskrypcje; płatności cykliczne"')
            .replace('"Portfele cyfrowe (Apple Pay, Google Pay)"', '"Portfele cyfrowe (Apple Pay; Google Pay)"')
            .encode("utf-8"),
            (),
        ),
        (
            b"\xef\xbb\xbf"
            + PL_TEXT.replace(";", "\t")
            .replace('"Subskrypcje\t płatności cykliczne"', '"Subskrypcje; płatności cykliczne"')
            .replace('"Portfele cyfrowe (Apple Pay\t Google Pay)"', '"Portfele cyfrowe (Apple Pay; Google Pay)"')
            .encode("utf-8"),
            (),
        ),
        (PL_TEXT.encode("cp1250"), ("--encoding", "cp1250")),
    ],
    ids=["comma", "tab-bom", "cp1250"],
)
def test_at_50_resaved_variants_equal_at_48(data: bytes, extra: tuple[str, ...]) -> None:
    io = _io(data)
    assert _pl(io, *extra) == 0, io.stderr
    assert io.stdout == _first_line_swapped(PL_YAML, "in.csv")


def test_at_50_cp1250_without_encoding_is_e102() -> None:
    io = _io(PL_TEXT.encode("cp1250"))
    assert _pl(io) == 1
    assert io.stdout == b""
    assert io.stderr.startswith("in.csv:1:21: error E102: cannot decode byte 0xF3 as utf-8 at line 1, byte 21; ")
    assert "try --encoding cp1250" in io.stderr


AT51 = {
    "a": (PL_TEXT.replace("Rozmiar", "Wielkość", 1), "E103", "1:1"),
    "b": (PL_TEXT.replace(";app;", ";Apka;"), "E030", "5:3"),
    "c": (PL_TEXT.replace(";S;app", ";XXXL;app"), "E031", "5:2"),
    "d": (PL_TEXT.replace(";tak;", ";może;"), "E011", "4:6"),
    "e": (PL_TEXT.replace("2027-03-15", "2027-13"), "E013", "5:4"),
    "f": (PL_TEXT.replace("Widżety Android;S;", "Widżety Android;;"), "E032", "5:2"),
    "g": (
        PL_TEXT.replace('"Portfele cyfrowe (Apple Pay; Google Pay)"', '"Portfele cyfrowe (Apple Pay; Google Pay)'),
        "E101",
        "6:1",
    ),
    "h": (
        PL_TEXT.replace("Widżety Android;S;app;2027-03-15;;;;", "Widżety Android;S;app;2027-03-15;;;;Ewa;x"),
        "E106",
        "5:9",
    ),
    "i": (PL_TEXT.replace("Opis;", "Name;", 1), "E104", "1:7"),
}


@pytest.mark.parametrize("case", sorted(AT51))
def test_at_51_invalid_csvs(case: str) -> None:
    text, code, where = AT51[case]
    io = _io(text.encode("utf-8"))
    assert _pl(io) == 1
    assert io.stdout == b""
    errors = [line for line in io.stderr.splitlines() if ": error " in line]
    assert len(errors) == 1, io.stderr
    assert errors[0].startswith(f"in.csv:{where}: error {code}: ")
    if case in "bcdef":
        assert errors[0].endswith("]") and '[column "' in errors[0]
    if case == "b":
        assert '(did you mean "app"?)' in errors[0]


