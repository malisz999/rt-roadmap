def test_at_55_stdin_twice() -> None:
    outs = []
    for _ in range(2):
        io = FakeIO(MINIMAL_CSV)
        assert main(["convert"], io) == 0
        outs.append(io.stdout)
        assert "from <stdin>" in io.stderr
    assert outs[0] == outs[1] == _first_line_swapped(MINIMAL_YAML, "<stdin>")


