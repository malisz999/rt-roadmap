def test_at_52_skeleton() -> None:
    io = _io(SKELETON.encode())
    assert main(["convert", "in.csv", "--slots", "2", "--team", "Zespół wspólny", "--title", "Plan Q1"], io) == 0
    out = io.stdout.decode()
    assert "title: Plan Q1\n" in out
    for sd in ("kanaly-platnosci", "merchant", "roadmap"):
        assert f"  - id: {sd}\n" in out
    for team in ("karty", "platnosci-lodz", "zespol-wspolny"):
        assert f"      - id: {team}\n" in out
    assert out.count("parallel_projects: 2\n") == 3
    assert "    size: M\n" in out and "size: m" not in out


def test_at_53_e107_e031_and_usage() -> None:
    io = _io((SKELETON + "Portal,S,Karty,Merchant\n").encode())
    assert main(["convert", "in.csv"], io) == 1
    assert _codes(io.stderr) == ["error E107"]
    assert 'team "Karty" is in subdomain "Kanały płatności" (line 2) and "Merchant" (line 6)' in io.stderr

    io = _io(b"name,size\nBig,L\nSmall,S\n")
    assert main(["convert", "in.csv", "--sizes", "S=2,M=5"], io) == 1
    assert _codes(io.stderr) == ["error E031"]

    io = _io(SKELETON.encode())
    assert main(["convert", "in.csv", "--base", "teams.base.yaml", "--slots", "2"], io) == 2
    assert io.stdout == b""


def test_at_54_team_from_base_option_or_e105() -> None:
    csv = b"name,size\nA,M\nB,S\n"
    io = _io(csv)
    assert main(["convert", "in.csv", "--base", "teams.base.yaml"], io) == 1
    assert _codes(io.stderr) == ["error E105", "error E105"]
    assert (
        "in.csv:2:1: error E105: row has no team and teams.base.yaml has 2 teams; add a team column or --team"
        in io.stderr
    )

    io = _io(csv)
    assert main(["convert", "in.csv", "--base", "teams.base.yaml", "--team", "app"], io) == 0
    assert io.stdout.decode().count("    team: app\n") == 2

    base = BASE.replace(b"projects: []", b"projects:\n  - name: Base project  # kept\n    team: blik\n    size: S\n")
    io = _io(csv, **{"one.yaml": base})
    argv = ["convert", "in.csv", "--base", "one.yaml", "--team", "Aplikacja mobilna", "--append"]
    assert main(argv, io) == 0, io.stderr
    out = io.stdout.decode()
    assert out.index("Base project  # kept") < out.index("- name: A\n") < out.index("- name: B\n")
    assert out.count("team: app") == 2


