"""convert.emit: dumper settings and header comment (RS CV-18), byte-compared with the expected files."""

from __future__ import annotations

from pathlib import Path

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq

from rt.convert.emit import display_name, dump, header_comment
from rt.convert.skeleton import Skeleton

FIX = Path(__file__).resolve().parents[2] / "docs" / "fixtures" / "convert"


def _project(
    name: str, team: str, *, start: str | None = None, size: str | None = None, **extra: object
) -> CommentedMap:
    p = CommentedMap()
    p["name"] = name
    p["team"] = team
    if start:
        p["start"] = start
    if size:
        p["size"] = size
    for k, v in extra.items():
        p[k] = v
    return p


def _flow(*items: str) -> CommentedSeq:
    seq = CommentedSeq(items)
    seq.fa.set_flow_style()
    return seq


def test_display_name() -> None:
    assert display_name("projects.pl.csv") == "projects.pl.csv"
    assert display_name("data/in/projects.csv") == "projects.csv"
    assert display_name(r"C:\data\projects.csv") == "projects.csv"
    assert display_name("<stdin>") == "<stdin>"
    assert header_comment("<stdin>") == "# Generated by rt convert from <stdin>. Edit freely.\n"


def test_skeleton_dump_equals_minimal_expected() -> None:
    sk = Skeleton()
    sk.add("Team", "Roadmap", 2)
    doc = sk.build()
    names = [
        ("Kreator onboardingu merchanta", "L"),
        ("Raporty i eksporty v2", "M"),
        ("Samoobsługowe zwroty", "S"),
        ("Pulpit wypłat", "M"),
    ]
    doc["projects"] = CommentedSeq(_project(n, "team", size=s) for n, s in names)
    expected = (FIX / "projects.minimal.expected.yaml").read_bytes()
    assert dump(doc, "dir/projects.minimal.csv").encode("utf-8") == expected


def test_base_dump_keeps_comments_and_equals_pl_expected() -> None:
    doc = YAML().load((FIX / "teams.base.yaml").read_text(encoding="utf-8"))
    doc["projects"] = CommentedSeq(
        [
            _project(
                "Płatności cykliczne BLIK",
                "blik",
                start="2027-01",
                size="L",
                description="Subskrypcje; płatności cykliczne",
            ),
            _project("BLIK w aplikacji", "app", size="M", depends_on=_flow("Płatności cykliczne BLIK")),
            _project("Utrzymanie aplikacji", "app", start="2027-02", ongoing=True),
            _project("Widżety Android", "app", start="2027-03", size="S"),
            _project(
                "Portfele cyfrowe (Apple Pay; Google Pay)",
                "blik",
                size="M",
                depends_on=_flow("Płatności cykliczne BLIK", "BLIK w aplikacji"),
            ),
        ]
    )
    expected = (FIX / "projects.pl.expected.yaml").read_bytes()
    assert dump(doc, "projects.pl.csv").encode("utf-8") == expected


def test_scalars_that_look_like_other_types_are_quoted_and_round_trip() -> None:
    doc = CommentedMap()
    values = ["yes", "123", "2027-01-15", "null", "a: b", "#x", "[x]", "Płatność, raty", "multi\nline"]
    doc["v"] = CommentedSeq(values)
    doc["deps"] = _flow("a, b", "c")
    text = dump(doc, "x.csv")
    loaded = YAML().load(text)
    assert list(loaded["v"]) == values
    assert list(loaded["deps"]) == ["a, b", "c"]
    assert "\r" not in text
