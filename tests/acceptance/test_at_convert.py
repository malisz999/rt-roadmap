def _with_first_line(expected: Path, source_name: str) -> bytes:
    data = expected.read_bytes()
    rest = data.split(b"\n", 1)[1]
    return f"# Generated by rt convert from {source_name}. Edit freely.\n".encode() + rest


def _pl_dir(tmp: Path) -> Path:
    copy_fixture(PL_CSV, tmp)
    copy_fixture(BASE, tmp)
    return tmp


