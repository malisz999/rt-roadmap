def test_at_54_team_resolution_with_base(tmp_path: Path) -> None:
    """AT-54: no team column + base with 2 teams -> E105 for every row; --team app -> every project
    team: app; --team "Aplikacja mobilna" --append with a base holding one project -> base project
    first, then the CSV rows."""
    copy_fixture(MIN_CSV, tmp_path)
    copy_fixture(BASE, tmp_path)
    r1 = run_rt(["convert", "projects.minimal.csv", "--base", "teams.base.yaml"], cwd=tmp_path)
    assert r1.code == 1, r1.describe()
    assert r1.stdout == b""
    e105 = [(d.file, d.line) for d in r1.diags if d.code == "E105"]
    assert e105 == [("projects.minimal.csv", n) for n in (2, 3, 4, 5)], r1.stderr
    assert [d.code for d in r1.diags if d.severity == "error"] == ["E105"] * 4

    r2 = run_rt(["convert", "projects.minimal.csv", "--base", "teams.base.yaml", "--team", "app"], cwd=tmp_path)
    assert r2.code == 0, r2.describe()
    doc2 = load_yaml(r2.stdout)
    assert [p["team"] for p in doc2["projects"]] == ["app"] * 4

    base_text = BASE.read_text(encoding="utf-8").replace(
        "projects: []\n",
        "projects:\n  - name: Istniejący projekt\n    team: blik\n    size: S\n    start: 2027-01\n",
    )
    (tmp_path / "base1.yaml").write_text(base_text, encoding="utf-8")
    r3 = run_rt(
        ["convert", "projects.minimal.csv", "--base", "base1.yaml", "--team", "Aplikacja mobilna", "--append"],
        cwd=tmp_path,
    )
    assert r3.code == 0, r3.describe()
    doc3 = load_yaml(r3.stdout)
    assert [p["name"] for p in doc3["projects"]] == [
        "Istniejący projekt",
        "Kreator onboardingu merchanta",
        "Raporty i eksporty v2",
        "Samoobsługowe zwroty",
        "Pulpit wypłat",
    ]
    assert [p["team"] for p in doc3["projects"]] == ["blik", "app", "app", "app", "app"]
    # without --append the base project is replaced
    r4 = run_rt(["convert", "projects.minimal.csv", "--base", "base1.yaml", "--team", "app"], cwd=tmp_path)
    assert r4.code == 0, r4.describe()
    assert next(p["name"] for p in load_yaml(r4.stdout)["projects"]) == "Kreator onboardingu merchanta"


