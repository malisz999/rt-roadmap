def test_at_49_convert_piped_into_render(tmp_path: Path) -> None:
    """AT-49: convert … | rt render --plan - -o pl.html -> exit 0; plan values; pl.html equals
    rendering out.yaml from AT-48."""
    _pl_dir(tmp_path)
    conv_args = ["convert", "projects.pl.csv", "--base", "teams.base.yaml", "--map", PL_MAP]
    up = subprocess.Popen(rt_cmd(conv_args), stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=tmp_path, env=rt_env())
    assert up.stdout is not None
    down = subprocess.Popen(
        rt_cmd(["render", "--plan", "-", "-o", "pl.html"]),
        stdin=up.stdout,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        cwd=tmp_path,
        env=rt_env(),
    )
    up.stdout.close()
    plan_bytes, err = down.communicate(timeout=120)
    assert up.wait(timeout=60) == 0
    assert down.returncode == 0, err.decode("utf-8", "replace")
    plan = load_json(plan_bytes)
    widz = plan_project(plan, 4)
    assert widz["name"] == "Widżety Android"
    assert (widz["team"], widz["lane"], widz["start"]) == ("app", 1, "2027-03-26")
    assert (widz["delay_days"], widz["delay_reason"]) == (25, "capacity")
    blik_app = plan_project(plan, 2)
    assert blik_app["name"] == "BLIK w aplikacji"
    assert "auto_start" in blik_app["flags"] and blik_app["start"] == "2027-02-26"
    portfele = plan_project(plan, 5)
    assert portfele["name"] == "Portfele cyfrowe (Apple Pay; Google Pay)"
    assert "auto_start" in portfele["flags"]
    assert (portfele["start"], portfele["team"], portfele["lane"]) == ("2027-03-26", "blik", 1)
    utrz = plan_project(plan, 3)
    assert (utrz["name"], utrz["team"], utrz["lane"]) == ("Utrzymanie aplikacji", "app", 2)
    assert "continues" in utrz["flags"]
    # CV-20: same HTML as converting to a file and rendering that file
    r1 = run_rt([*conv_args, "-o", "out.yaml"], cwd=tmp_path)
    assert r1.code == 0, r1.describe()
    r2 = run_rt(["render", "out.yaml", "-o", "file.html"], cwd=tmp_path)
    assert r2.code == 0, r2.describe()
    assert (tmp_path / "pl.html").read_bytes() == (tmp_path / "file.html").read_bytes()


