    assert "0xf3" in r.diags[0].message.lower(), r.diags[0].message
    ok = run_rt(["convert", name, "--base", "teams.base.yaml", "--map", PL_MAP, "--encoding", "cp1250"], cwd=tmp_path)
    assert ok.code == 0, ok.describe()
    assert ok.stdout == _with_first_line(PL_EXPECTED, name)


