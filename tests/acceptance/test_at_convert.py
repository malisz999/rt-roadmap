@pytest.mark.parametrize("case", sorted(AT51), ids=sorted(AT51))
def test_at_51_invalid_csvs(tmp_path: Path, case: str) -> None:
    """AT-51: nine invalid CSVs -> exit 1; stdout empty; codes E103, E030 (+suggestion), E031, E011,
    E013, E032, E101, E106, E104; positions are CSV line and field number; cell messages end with
    [column "…"]."""
    text, extra, use_base, code, line, col, header = AT51[case]
    name = f"{case}.csv"
    (tmp_path / name).write_text(text, encoding="utf-8")
    args = ["convert", name, *extra]
    if use_base:
        copy_fixture(BASE, tmp_path)
        args += ["--base", "teams.base.yaml"]
    r = run_rt(args, cwd=tmp_path)
    assert r.code == 1, r.describe()
    assert r.stdout == b""
    errors = [d for d in r.diags if d.severity == "error"]
    assert [d.code for d in errors] == [code], r.stderr
    d = errors[0]
    assert d.file == name
    assert d.line == line, r.stderr
    if col is not None:
        assert d.col == col, r.stderr
    if header is not None:
        assert d.message.endswith(f'[column "{header}"]'), d.message
    if code == "E030":
        assert "did you mean" in d.message, d.message
    if code == "E103":
        assert '"size"' in d.message and "--map" in d.message, d.message
    assert sorted(p.name for p in tmp_path.iterdir()) == sorted([name] + (["teams.base.yaml"] if use_base else []))


