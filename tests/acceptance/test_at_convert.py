def test_at_48_polish_csv_with_base(tmp_path: Path) -> None:
    """AT-48: convert projects.pl.csv --base teams.base.yaml --map … -o out.yaml -> exit 0; out.yaml
    byte-equal to projects.pl.expected.yaml; W020 at 1:8 and W021 at 5:4; both base comments present."""
    _pl_dir(tmp_path)
    r = run_rt(
        ["convert", "projects.pl.csv", "--base", "teams.base.yaml", "--map", PL_MAP, "-o", "out.yaml"], cwd=tmp_path
    )
    assert r.code == 0, r.describe()
    assert r.stdout == b""
    out = (tmp_path / "out.yaml").read_bytes()
    assert out.decode("utf-8") == PL_EXPECTED.read_text(encoding="utf-8")
    assert out == PL_EXPECTED.read_bytes()
    diags = [(d.file, d.line, d.col, d.severity, d.code) for d in r.diags]
    assert diags == [
        ("projects.pl.csv", 1, 8, "warning", "W020"),
        ("projects.pl.csv", 5, 4, "warning", "W021"),
    ], r.stderr
    w020 = r.diags[0].message
    assert w020.startswith('column "Właściciel" is not used and was ignored'), w020
    w021 = r.diags[1].message
    assert w021 == 'day of "2027-03-15" ignored; using 2027-03 [column "Start"]', w021
    assert "rt: wrote out.yaml — 5 projects from projects.pl.csv, 2 warnings" in r.stderr
    text = out.decode("utf-8")
    assert "# Base file for rt convert: everything except the project list.\n" in text
    assert "# Projects come from a spreadsheet export (projects.pl.csv).\n" in text
    assert "parallel_projects: 2   # two projects at a time\n" in text


