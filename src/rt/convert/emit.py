"""YAML emission for rt convert: dumper settings and the header comment (RS CV-18; ADS 6.8 step 8).

ruamel's emitter needs about 0.2 ms per project, too slow for a 10,000-row CSV (RS NF-11). Project mappings built
by rt convert are flat (plain strings, `true`, flow lists of strings), so `dump` writes them directly whenever
every scalar is one that ruamel itself would write plain, and lets ruamel write everything else: the rest of the
document, and any project holding a scalar that needs quoting. The two paths are byte-identical (tested).
"""

from __future__ import annotations

import io
from pathlib import PurePath, PurePosixPath, PureWindowsPath
from typing import Any

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap, CommentedSeq
from ruamel.yaml.emitter import Emitter
from ruamel.yaml.nodes import ScalarNode

from rt.io.streams import STDIN_NAME

_STR_TAG = "tag:yaml.org,2002:str"
_PLACEHOLDER = "rt-convert-projects-placeholder-7f3e"
_ITEM_INDENT = "  - "  # sequence=4, offset=2 under a top-level key
_KEY_INDENT = "    "
_MAX_FAST_LINE = 1000  # far below the 4096 width, so ruamel would never fold such a line


def make_yaml() -> YAML:
    """Round-trip dumper: mappings 2, sequences 4 with offset 2, no wrapping, Polish letters as-is."""
    yaml = YAML(typ="rt")
    yaml.indent(mapping=2, sequence=4, offset=2)
    yaml.width = 4096
    yaml.allow_unicode = True
    return yaml


def display_name(source: str) -> str:
    """The CSV name without directories (either separator), or `<stdin>`."""
    if source == STDIN_NAME:
        return source
    path: PurePath = PureWindowsPath(source) if "\\" in source else PurePosixPath(source)
    return path.name or source


def header_comment(source: str) -> str:
    return f"# Generated by rt convert from {display_name(source)}. Edit freely.\n"


def dump(doc: Any, source: str) -> str:
    """The complete output text: header comment, then the document (LF line endings)."""
    return header_comment(source) + _FastDumper().dump(doc)


def dump_slow(doc: Any) -> str:
    """The document written by ruamel alone (the reference for the fast path)."""
    buf = io.StringIO()
    make_yaml().dump(doc, buf)
    return buf.getvalue()


class _FastDumper:
    def __init__(self) -> None:
        self.yaml = make_yaml()
        self.resolver = self.yaml.resolver
        self.emitter = Emitter(None, allow_unicode=True)
        # Without a dumper the emitter is its own serializer; analyze_scalar reads the YAML version from it.
        self.emitter.use_version = None  # type: ignore[attr-defined]
        self.plain_cache: dict[tuple[str, bool], bool] = {}

    def _plain(self, value: str, flow: bool) -> bool:
        """Would ruamel write this string plain in a block mapping value (or a flow sequence item)?"""
        key = (value, flow)
        hit = self.plain_cache.get(key)
        if hit is None:
            hit = False
            if self.resolver.resolve(ScalarNode, value, (True, False)) == _STR_TAG:
                analysis = self.emitter.analyze_scalar(value)
                hit = bool(analysis.allow_flow_plain if flow else analysis.allow_block_plain) and not analysis.empty
            self.plain_cache[key] = hit
        return hit

    def _project_lines(self, project: Any) -> list[str] | None:
        """`key: value` lines of a flat project mapping, or None when ruamel must write it."""
        if not isinstance(project, CommentedMap) or project.ca.items or project.ca.comment or len(project) == 0:
            return None
        lines: list[str] = []
        for key, value in project.items():
            if not isinstance(key, str) or not self._plain(key, False) or ":" in key:
                return None
            if value is True:
                text = "true"
            elif type(value) is str:
                if not self._plain(value, False):
                    return None
                text = value
            elif isinstance(value, CommentedSeq) and value.fa.flow_style() and len(value) > 0 and not value.ca.items:
                items = list(value)
                if not all(type(i) is str and self._plain(i, True) for i in items):
                    return None
                text = "[" + ", ".join(items) + "]"
            else:
                return None
            line = f"{key}: {text}"
            if len(line) > _MAX_FAST_LINE:
                return None
            lines.append(line)
        return lines

    def _project_text(self, project: Any) -> str:
        lines = self._project_lines(project)
        if lines is None:
            # ruamel writes this one in the same context: an item of a top-level `projects` block sequence.
            mini = CommentedMap()
            mini["projects"] = CommentedSeq([project])
            text = self._ruamel(mini)
            return text.removeprefix("projects:\n")
        head, *rest = lines
        return "".join([_ITEM_INDENT, head, "\n", *(f"{_KEY_INDENT}{line}\n" for line in rest)])

    def _ruamel(self, doc: Any) -> str:
        buf = io.StringIO()
        self.yaml.dump(doc, buf)
        return buf.getvalue()

    def dump(self, doc: Any) -> str:
        projects = doc.get("projects") if isinstance(doc, CommentedMap) else None
        if (
            not isinstance(projects, CommentedSeq)
            or len(projects) == 0
            or projects.fa.flow_style()
            or projects.ca.items
            or projects.ca.comment
            or "projects" in doc.ca.items
        ):
            return self._ruamel(doc)
        placeholder = CommentedSeq([_PLACEHOLDER])
        doc["projects"] = placeholder
        try:
            skeleton = self._ruamel(doc)
        finally:
            doc["projects"] = projects
        marker = f"\nprojects:\n{_ITEM_INDENT}{_PLACEHOLDER}\n"
        if skeleton.count(_PLACEHOLDER) != 1 or marker not in skeleton:
            return self._ruamel(doc)
        body = "".join(self._project_text(p) for p in projects)
        before, after = skeleton.split(marker)
        return f"{before}\nprojects:\n{body}{after}"
